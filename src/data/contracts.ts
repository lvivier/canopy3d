export function createSandboxContract(opts: {
  species: SpeciesId;
  site: SiteId;
  weather: WeatherId;
  windSpeed: number;
  seed?: number;
}): ContractSpec {
  const seed = opts.seed ?? Math.floor(Math.random() * 90000) + 1000;
  const heightBySpecies: Record<SpeciesId, number> = {
    douglas_fir: 26,
    western_red_cedar: 22,
    sitka_spruce: 23,
    bigleaf_maple: 18,
    red_alder: 16,
    western_hemlock: 22,
  };
  const h = heightBySpecies[opts.species];
  return {
    id: `sandbox-${opts.species}-${seed}`,
    index: 0,
    title: 'Free-Cut Sandbox',
    subtitle: 'Practice Pruning, Directional Felling, Wedges & Bucking',
    site: opts.site,
    weather: opts.weather,
    difficulty: 2,
    windSpeed: opts.windSpeed,
    windAngle: 0.7,
    unlockedTools: ['prune', 'fell', 'wedge', 'buck'],
    briefing:
      'Practice freely with all tools unlocked! Prune limbs to shift lean, experiment with face notches and wedges, drop into the target corridor, and buck the trunk.',
    tips: [
      'Switch tools anytime along the bottom dock.',
      'Right-click drag to orbit, scroll to zoom.',
    ],
    basePayout: 500,
    isSandbox: true,
    hazards: [
      { id: 'sb-shed', label: 'Woodshed', type: 'shed', x: -11.5, z: -7.5, radius: 3.5, width: 4.6, depth: 3.6, rotation: 0.2 },
      { id: 'sb-sap', label: 'Protected Sapling', type: 'sapling', x: -6.5, z: 11.0, radius: 2.4 },
    ],
    trees: [
      {
        id: 'sb-tree-1',
        species: opts.species,
        x: 0,
        z: 0,
        height: h,
        leanAngle: -2.2,
        leanStrength: 0.28 + opts.windSpeed * 0.2,
        task: 'prune_and_fell',
        hazardBranches: 4,
        hazardBranchAngle: -2.2,
        dropZone: { x: h * 0.45, z: 2.5, angle: 0.22, length: h + 1.5, width: 6.2, label: 'Target Drop Zone' },
        requireBucking: true,
        seed,
      },
    ],
  };
}
